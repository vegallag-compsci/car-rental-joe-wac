-- ---------------------------------------------------------------------------
-- 2. Tables
-- ---------------------------------------------------------------------------

create table car_categories (
  id   integer generated by default as identity primary key,
  name text not null unique
);

create table cars (
  id           bigint generated by default as identity primary key,
  category_id  integer not null references car_categories (id),
  make         text    not null,
  model        text    not null,
  year         integer not null check (year between 1980 and 2100),
  color        text    not null,
  seats        integer not null check (seats > 0),

  -- NOTE: 'AutoManual' is only here because car id 2 in the mock data uses it.
  -- Our documented contract is 'automatic' | 'manual'. Once that row is fixed,
  -- tighten this with:
  --   alter table cars drop constraint cars_transmission_check;
  --   alter table cars add constraint cars_transmission_check
  --     check (transmission in ('automatic','manual'));
  transmission text not null
               check (transmission in ('automatic', 'manual', 'AutoManual')),

  mileage      integer not null default 0 check (mileage >= 0),
  daily_rate   numeric(10,2) not null check (daily_rate > 0),
  image_url    text,
  is_active    boolean not null default true,
  created_at   timestamptz not null default now()
);

create index cars_category_id_idx on cars (category_id);
create index cars_is_active_idx   on cars (is_active);

create table bookings (
  id          bigint generated by default as identity primary key,

  -- Nullable for now: the seed bookings predate auth, so they have no owner.
  -- After auth is wired up and every row has a user, make it required:
  --   alter table bookings alter column user_id set not null;
  user_id     uuid references auth.users (id) on delete cascade,

  car_id      bigint not null references cars (id),
  pickup_at   date    not null,
  return_at   date    not null,
  status      text    not null default 'pending'
              check (status in ('pending','confirmed','active','returned','cancelled')),
  total_price numeric(10,2) not null check (total_price >= 0),
  created_at  timestamptz not null default now(),

  constraint bookings_dates_ordered check (return_at > pickup_at)
);

create index bookings_car_id_idx  on bookings (car_id);
create index bookings_user_id_idx on bookings (user_id);


