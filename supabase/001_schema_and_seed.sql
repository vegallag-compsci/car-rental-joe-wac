-- ---------------------------------------------------------------------------
-- 6. Resync the identity sequences
--
-- REQUIRED. We inserted explicit ids, so the sequences still start at 1 and
-- the next natural insert would collide with an existing row. This pushes
-- each sequence past the highest id currently in the table.
-- ---------------------------------------------------------------------------
select setval(pg_get_serial_sequence('car_categories', 'id'),
              coalesce((select max(id) from car_categories), 1));
select setval(pg_get_serial_sequence('cars', 'id'),
              coalesce((select max(id) from cars), 1));
select setval(pg_get_serial_sequence('bookings', 'id'),
              coalesce((select max(id) from bookings), 1));


-- ---------------------------------------------------------------------------
-- 7. Prevent double-booking at the database level
--
-- Two users can both pass an availability check and then both insert. No
-- amount of application code fixes that race — the database has to reject it.
-- This makes overlapping live bookings for the same car impossible.
--
-- The '[)' bound means a booking ending the same day another starts is
-- allowed, which is what we want.
-- ---------------------------------------------------------------------------
create extension if not exists btree_gist;

alter table bookings add constraint bookings_no_overlap
  exclude using gist (
    car_id WITH =,
    daterange(pickup_at, return_at, '[)') WITH &&
  ) where (status in ('pending', 'confirmed', 'active'));


